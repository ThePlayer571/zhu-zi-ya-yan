# =============================================================================
# 句读 (punctuation)
# =============================================================================

# 终止符 — 每条语句必须以终止符结尾
STATEMENT_TERMINATORS = frozenset({'。', '？', '！'})

# 断句符 — 语句内部用于断句
CLAUSE_SEPARATORS = frozenset({'，', '、'})

# 所有句读符号（终止符 + 断句符）
PUNCTUATION = STATEMENT_TERMINATORS | CLAUSE_SEPARATORS

# =============================================================================
# 书名号 — 用于标识函数名
# =============================================================================

LEFT_BOOK_TITLE = '《'
RIGHT_BOOK_TITLE = '》'

# =============================================================================
# 变量名 — 所有变量名均须以"子"结尾
# =============================================================================

VARIABLE_SUFFIX = '子'

# =============================================================================
# 非负整数字面量字符集
# =============================================================================

# 数字字
DIGIT_CHARS = frozenset({'一', '二', '三', '四', '五', '六', '七', '八', '九'})

# 进位字
CARRY_CHARS = frozenset({'十', '百', '千', '万', '亿', '兆'})

# 连接字 — 分隔独立数值，表示加法
CONNECT_CHARS = frozenset({'有', '又'})

# 占位字 — 显式补零
ZERO_CHAR = '零'

# 非负整数字面量的完整字符集合
INTEGER_LITERAL_CHARS = DIGIT_CHARS | CARRY_CHARS | CONNECT_CHARS | {ZERO_CHAR}

# =============================================================================
# 非负浮点数字面量字符集 — 在整数字符集基础上增加小数位字
# =============================================================================

# 小数位字（十分位 ~ 万分位）
DECIMAL_PLACE_CHARS = frozenset({'秒', '厘', '忽', '微'})

# 非负浮点数字面量的完整字符集合
FLOAT_LITERAL_CHARS = INTEGER_LITERAL_CHARS | DECIMAL_PLACE_CHARS

# =============================================================================
# 布尔值字面量
# =============================================================================

BOOL_TRUE_CHARS = frozenset({'是', '然'})
BOOL_FALSE_CHARS = frozenset({'否', '非'})

# =============================================================================
# 注释 — 古文注疏风格的注释系统
# =============================================================================

# 注释定义/注解的括号
LEFT_ANNOTATION = '【'
RIGHT_ANNOTATION = '】'

# 注解关键字 — 分隔注释标识符与注解内容
ANNOTATION_SEPARATOR = '：'